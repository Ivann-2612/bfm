import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";

const out = "supabase/functions/_shared";
mkdirSync(out, { recursive: true });

copyFileSync("content/sr.json", `${out}/sr.json`);
copyFileSync("content/en.json", `${out}/en.json`);

const fix = (src) =>
  src
    .replace(/^import "server-only";\r?\n/m, "")
    .replace(
      /from "@content\/(sr|en)\.json";/g,
      'from "./$1.json" with { type: "json" };',
    )
    .replace(/from "\.\.\/content"/g, 'from "./content.ts"')
    .replace(/from "\.\/content"/g, 'from "./content.ts"')
    .replace(/from "\.\.\/pricing"/g, 'from "./pricing.ts"')
    .replace(/from "zod"/g, 'from "npm:zod@4"')
    .replace(/from "resend"/g, 'from "npm:resend@6"')
    .replace(/process\.env\.([A-Z_]+)/g, 'Deno.env.get("$1")');

for (const [from, to] of [
  ["src/lib/content.ts", "content.ts"],
  ["src/lib/pricing.ts", "pricing.ts"],
  ["src/lib/schema.ts", "schema.ts"],
  ["src/lib/server/mail.ts", "mail.ts"],
]) {
  writeFileSync(
    `${out}/${to}`,
    "// GENERATED by scripts/sync-functions.mjs — edit the original in src/\n" +
      fix(readFileSync(from, "utf8")),
  );
}

console.log("synced", out);
