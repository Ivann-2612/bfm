import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const out = "supabase/functions/_shared";
mkdirSync(out, { recursive: true });

copyFileSync("content/sr.json", `${out}/sr.json`);
copyFileSync("content/en.json", `${out}/en.json`);

const fix = (src) =>
  src
    .replace(/from "@content\/(sr|en)\.json";/g, 'from "./$1.json" with { type: "json" };')
    .replace(/from "\.\/(content|pricing)";/g, 'from "./$1.ts";')
    .replace(/from "zod";/g, 'from "npm:zod@4";');

for (const name of ["content", "pricing", "schema", "tickets"]) {
  const src = fix(readFileSync(`src/lib/${name}.ts`, "utf8"));
  if (/from "@|process\.env|server-only/.test(src)) throw new Error(`${name}.ts has an import or API the functions can't use`);
  writeFileSync(`${out}/${name}.ts`, `// GENERATED by scripts/sync-functions.mjs from src/lib/${name}.ts — edit the original.\n${src}`);
}
console.log(`synced ${out}`);
